// W.A.P. to print 1 to 10 (for loop)
/*
Algorithm:
Step 1: Start
Step 2: Loop i from 1 to 10
Step 3: Print i
Step 4: End

Program Name: Print 1 to 10
Description: Simple counting
Concepts Used: for loop
*/
#include <iostream>
using namespace std;
int main() {
    for (int i = 1; i <= 10; i++) {
        cout << i << " ";
    }
    cout << "\n\n--- BioAlign-Pro ---" << endl;
    return 0;
}
