// W.A.P. to demo For Loops
/*
Program Name: Print 1 to 10 (for)
Description: Basic iterative looping with initialization, condition, and increment.
Concepts Used: For Loops
*/

#include <iostream>
using namespace std;
int main() {
    for (int i = 1; i <= 10; i++) {
        cout << i << " ";
    }
    return 0;
}
